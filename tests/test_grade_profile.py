class TestUpgradeLegality(unittest.TestCase):
    def _rec_with_upgrade(self, design, downgrade):
        rec = load_record()
        r = rec["results"][0]
        r["design_mix"] = {"rct": 0, "nrsi": 0, "observational": 4, "case_series": 0} \
            if design == "observational" else {"rct": 4, "nrsi": 0, "observational": 0, "case_series": 0}
        r["starting_level"] = "low" if design == "observational" else "high"
        for name in gp.DOMAINS:
            r["domains"][name]["rating"] = -1 if (downgrade and name == "inconsistency") else 0
        r["upgrades"] = {"large_effect": 1, "dose_response": 0, "opposing_confounding": 0}
        start = gp.LEVELS[r["starting_level"]]
        r["final"] = gp.LEVEL_NAMES[max(1, min(4, start + (-1 if downgrade else 0) + 1))]
        return rec

    def test_upgrade_on_observational_with_no_downgrade_is_legal(self):
        code, out, _ = run(self._write(self._rec_with_upgrade("observational", False)),
                           "--rob", str(ROB_VALID), "--strict")
        self.assertEqual(code, 0, msg=out)

    def test_upgrade_on_randomized_body_is_flagged(self):
        code, out, _ = run(self._write(self._rec_with_upgrade("rct", False)),
                           "--rob", str(ROB_VALID), "--strict")
        self.assertEqual(code, 1)
        self.assertIn("only for non-randomized evidence", out)

    def test_upgrade_over_a_downgrade_is_flagged(self):
        code, out, _ = run(self._write(self._rec_with_upgrade("observational", True)),
                           "--rob", str(ROB_VALID), "--strict")
        self.assertEqual(code, 1)
        self.assertIn("unresolved serious concerns", out)

    def _write(self, rec):
        import tempfile
        d = tempfile.TemporaryDirectory()
        self.addCleanup(d.cleanup)
        p = pathlib.Path(d.name) / "rec.json"
        p.write_text(json.dumps(rec), encoding="utf-8")
        return p


