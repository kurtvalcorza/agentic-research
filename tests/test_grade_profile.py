class TestCoercion(unittest.TestCase):
    """Must agree with prisma_flow.py — see contracts/cli-contract.md."""

    def test_rejects_bool(self):
        with self.assertRaises(gp.InputError):
            gp._int(True, "x")

    def test_rejects_numeric_string(self):
        with self.assertRaises(gp.InputError):
            gp._int("3", "x")

    def test_rejects_non_integral_float(self):
        with self.assertRaises(gp.InputError):
            gp._int(3.5, "x")

    def test_rejects_negative(self):
        with self.assertRaises(gp.InputError):
            gp._int(-1, "x")

    def test_rejects_non_finite(self):
        for bad in (float("nan"), float("inf")):
            with self.subTest(value=bad), self.assertRaises(gp.InputError):
                gp._int(bad, "x")

    def test_rating_rejects_half_steps(self):
        for bad in (-0.5, -3, 1, True):
            with self.subTest(value=bad), self.assertRaises(gp.InputError):
                gp._rating(bad, "x")


