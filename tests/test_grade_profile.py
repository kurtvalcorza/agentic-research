"""Coverage for skills/validate-evidence/scripts/grade_profile.py.

Asserts the rules in specs/001-standards-enforcement-parity/contracts/grade-profile.md.
Each defect fixture carries exactly ONE defect, so a failure identifies its own cause.
Standard library only.
"""
from __future__ import annotations

import io
import json
import pathlib
import sys
import unittest
from contextlib import redirect_stdout, redirect_stderr
from unittest import mock

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from _load import load, fixture  # noqa: E402

gp = load("skills/validate-evidence/scripts/grade_profile.py")

VALID = fixture("grade-profile.valid.json")
ROB_VALID = fixture("risk-of-bias.valid.json")
ROB_HIGH = fixture("risk-of-bias.mostly-high.json")
ROB_UNCONFIRMED = fixture("risk-of-bias.unconfirmed.json")


def run(record_path, *args):
    """Invoke main() and return (exit_code, stdout, stderr)."""
    out, err = io.StringIO(), io.StringIO()
    argv = ["grade_profile.py", str(record_path), *args]
    with mock.patch.object(sys, "argv", argv), redirect_stdout(out), redirect_stderr(err):
        code = gp.main()
    return code, out.getvalue(), err.getvalue()


def load_record(name="grade-profile.valid.json"):
    return json.loads(fixture(name).read_text(encoding="utf-8"))


class TestValidRecord(unittest.TestCase):
    def test_valid_record_passes_with_rob(self):
        code, out, err = run(VALID, "--rob", str(ROB_VALID), "--strict")
        self.assertEqual(code, 0, msg=out + err)
        self.assertIn("✅", out)

    def test_emits_both_artifacts(self):
        _, out, _ = run(VALID, "--rob", str(ROB_VALID))
        self.assertIn("## Evidence profile", out)
        self.assertIn("## Summary of findings", out)

    def test_declares_synthesis_mode(self):
        _, out, _ = run(VALID, "--rob", str(ROB_VALID))
        self.assertIn("protocol outcomes", out)

    def test_theme_mode_is_labelled_as_an_adaptation(self):
        rec = load_record()
        rec["synthesis_mode"] = "theme"
        _, out, _ = run(self._tmp(rec, "theme.json"), "--rob", str(ROB_VALID))
        self.assertIn("SWiM adaptation", out)
        self.assertIn("synthesis themes", out)
        self.assertIn("not GRADE as published", out)

    def test_carries_provenance_line(self):
        _, out, _ = run(VALID, "--rob", str(ROB_VALID))
        self.assertIn("Generated by `grade_profile.py`", out)

    def test_states_what_it_cannot_verify(self):
        _, out, _ = run(VALID, "--rob", str(ROB_VALID))
        self.assertIn("cannot verify that a domain judgment was the", out)

    def _tmp(self, rec, name):
        import tempfile
        d = tempfile.TemporaryDirectory()
        self.addCleanup(d.cleanup)
        p = pathlib.Path(d.name) / name
        p.write_text(json.dumps(rec), encoding="utf-8")
        return p


class TestGoldenOutput(unittest.TestCase):
    """Pin the generated artifact so a refactor cannot quietly change what reviewers see.

    The provenance line embeds the invocation's source path, so the comparison
    covers everything above it.
    """

    def test_generated_artifact_matches_golden(self):
        _, out, _ = run(VALID, "--rob", str(ROB_VALID))
        actual = out.split("\n---\n\n*Generated by")[0].rstrip() + "\n"
        expected = fixture("grade-profile.valid.golden.md").read_text(encoding="utf-8")
        self.assertEqual(actual, expected)


class TestMalformedInput(unittest.TestCase):
    """Exit 2 — the record cannot be read. Distinct from a review being wrong."""

    def assert_malformed(self, name, *needles):
        code, out, err = run(fixture(name), "--rob", str(ROB_VALID), "--strict")
        self.assertEqual(code, 2, msg=f"expected exit 2 for {name}, got {code}")
        for n in needles:
            self.assertIn(n, err)
        # A record that cannot be read must not produce an authoritative-looking artifact.
        self.assertNotIn("## Evidence profile", out)

    def test_missing_schema_version(self):
        self.assert_malformed("grade-profile.no-version.json", "schema_version")

    def test_typo_domain_is_malformed_not_missing(self):
        """The distinction that matters most.

        A misspelled domain key reported as a *missing domain* would send the
        reviewer to add a domain they already wrote, and the typo would survive.
        """
        code, _, err = run(fixture("grade-profile.typo-domain.json"), "--strict")
        self.assertEqual(code, 2)
        self.assertIn("indirectnes", err)
        self.assertIn("unrecognised key", err)
        self.assertNotIn("missing downgrade domain", err)

    def test_aggregate_certainty_rejected(self):
        self.assert_malformed("grade-profile.aggregate-certainty.json",
                              "overall_certainty", "aggregated")

    def test_illegal_upgrade_key_rejected(self):
        self.assert_malformed("grade-profile.illegal-upgrade.json",
                              "importance_of_findings", "unrecognised key")

    def test_quoted_count_rejected(self):
        self.assert_malformed("grade-profile.quoted-count.json", "must be a JSON number")

    def test_empty_results_rejected(self):
        self.assert_malformed("grade-profile.empty-results.json", "nothing to check")

    def test_duplicate_study_id_rejected(self):
        self.assert_malformed("grade-profile.duplicate-study-id.json", "duplicate identifier")

    def test_invalid_json_exits_two(self):
        out, err = io.StringIO(), io.StringIO()
        stdin = io.StringIO("{not json")
        with mock.patch.object(sys, "argv", ["grade_profile.py"]), \
                mock.patch.object(sys, "stdin", stdin), \
                redirect_stdout(out), redirect_stderr(err):
            code = gp.main()
        self.assertEqual(code, 2)
        self.assertIn("not valid JSON", err.getvalue())


