class TestArtifactPreservesIdentity(_Tmp):
    """Round 7: identity is (study, result), so every artifact row must say which
    result it assesses. Without it, one study appraised for two outcomes renders
    two rows labelled 'R1' carrying different judgments."""

    def test_traffic_light_rows_are_distinguishable(self):
        _, out, _ = run(fixture("risk-of-bias.multi-result.json"))
        light = out.split("## Traffic-light summary", 1)[1]
        rows = [ln for ln in light.splitlines() if ln.startswith("| R1 |")]
        self.assertEqual(len(rows), 2, msg=light)
        self.assertNotEqual(rows[0], rows[1])
        self.assertIn("diagnostic accuracy at 12 months", rows[0])
        self.assertIn("quality of life at 12 months", rows[1])

    def test_every_traffic_light_table_carries_the_result(self):
        """Including the QUADAS-2 applicability table, which is a second grid."""
        _, out, _ = run(ALL_INSTRUMENTS)
        light = out.split("## Traffic-light summary", 1)[1]
        headers = [ln for ln in light.splitlines() if ln.startswith("| Study |")]
        self.assertEqual(len(headers), 5, msg="4 instruments + quadas2 applicability")
        for h in headers:
            self.assertIn("Result assessed", h)

    def test_header_separates_appraisals_from_studies(self):
        """Round 8: len(studies) counts appraisals. Reporting it as a study count
        inflates a manuscript-facing figure the moment a study has two results."""
        _, out, _ = run(fixture("risk-of-bias.multi-result.json"))
        self.assertIn("2 appraisals of 1 study", out)

    def test_header_counts_agree_when_each_study_has_one_result(self):
        _, out, _ = run(fixture("risk-of-bias.contract-example.json"))
        self.assertIn("4 appraisals of 4 studies", out)

    def test_h_rob_is_labelled_as_appraisals(self):
        """It has always counted appraisals: a human confirms a judgment about one
        result, not a study wholesale. Only the noun was wrong."""
        _, out, _ = run(fixture("risk-of-bias.unconfirmed-study.json"))
        self.assertIn("**H_rob: 1** appraisal awaiting", out)

    def test_violations_name_the_appraisal_not_just_the_study(self):
        """Round 9: with two appraisals of one study and only one at fault,
        'study R1' cannot tell the reviewer which judgment to go and fix."""
        code, out, _ = run(
            fixture("risk-of-bias.multi-result-partial-confirm.json"), "--strict")
        self.assertEqual(code, 1)
        faults = [ln for ln in out.splitlines() if ln.startswith("- study R1")]
        self.assertEqual(len(faults), 1, msg=out)
        self.assertIn("quality of life at 12 months", faults[0])
        self.assertNotIn("diagnostic accuracy", faults[0])
        self.assertIn("**H_rob: 1**", out)

    def test_every_violation_carries_the_result(self):
        """Not only the confirmation gate — the same ambiguity affects any
        per-appraisal violation once judgments differ by result."""
        for name in ("risk-of-bias.wrong-instrument.json",
                     "risk-of-bias.missing-domain.json",
                     "risk-of-bias.overall-too-favourable.json",
                     "risk-of-bias.nos-band-mismatch.json",
                     "risk-of-bias.no-info-but-low.json"):
            with self.subTest(fixture=name):
                _, out, _ = run(fixture(name))
                for ln in out.splitlines():
                    if ln.startswith("- study "):
                        self.assertIn("(result: ", ln)

    def test_result_rendered_even_when_the_instrument_mismatches(self):
        """The mismatch path skips domain validation, so it renders separately and
        would otherwise miss the column."""
        _, out, _ = run(fixture("risk-of-bias.wrong-instrument.json"))
        light = out.split("## Traffic-light summary", 1)[1]
        for ln in light.splitlines():
            if ln.startswith("| R1 |"):
                self.assertIn("diagnostic accuracy at 12 months", ln)


