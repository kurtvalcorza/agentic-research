"""Coverage for skills/appraise-risk-of-bias/scripts/rob_appraisal.py.

Asserts the rules in specs/001-standards-enforcement-parity/contracts/risk-of-bias.md
across all four instruments. Standard library only.
"""
from __future__ import annotations

import io
